#!/usr/bin/env python3
"""Generate the Arcade design kit from design/tokens.json (Python stdlib only).

    python3 design/generate.py           # write every generated file
    python3 design/generate.py --check   # fail if a generated file is out of date

Inputs: design/tokens.json, design/icons/icons.json, design/glyphs/*.svg,
design/css/components.css, design/shortcuts.json and spec/app-dirs.json.
Outputs are listed in OUTPUTS below; they are committed, and CI runs --check.
Validation (contrast pairs, the accent-soft formula, shortcut clashes, no
literal colours or px font sizes in the component CSS) fails before anything
is written. Output is deterministic: same inputs, same bytes.
"""
from __future__ import annotations

