def outputs() -> dict[Path, str]:
    tokens = json.loads((DESIGN / "tokens.json").read_text(encoding="utf-8"))
    icons = json.loads((DESIGN / "icons/icons.json").read_text(encoding="utf-8"))
    shortcuts = json.loads((DESIGN / "shortcuts.json").read_text(encoding="utf-8"))
    dirs = json.loads((ROOT / "spec/app-dirs.json").read_text(encoding="utf-8"))
    components = (DESIGN / "css/components.css").read_text(encoding="utf-8")
    errors, used = validate(tokens, shortcuts, components)
    if errors:
        raise TokenError("\n".join(errors))
    for name, d, _ in icon_entries(icons):
        normalise(d)  # every icon must parse
    if sorted(dirs["apps"]) != sorted(tokens["accent"]):
        raise TokenError("spec/app-dirs.json must list every app in tokens.json")
    files = {
        DESIGN / "css/arcade.css": emit_css(tokens, components),
        DESIGN / "css/icons.ts": emit_icons_ts(icons),
        DESIGN / "qml/Arcade/Theme.qml": emit_qml_theme(tokens),
        DESIGN / "qml/Arcade/Icon.qml": emit_qml_icon(icons),
        DESIGN / "qml/Arcade/IconData.js": emit_qml_icon_data(icons),
        DESIGN / "qml/Arcade/Fonts.qml": emit_qml_fonts(),
        DESIGN / "qml/Arcade/qmldir": emit_qmldir(),
        DESIGN / "qml/Arcade/Format.js": emit_qml_format((DESIGN / "css/format.ts").read_text(encoding="utf-8")),
        DESIGN / "dart/arcade_theme.dart": emit_dart_theme(tokens),
        DESIGN / "dart/arcade_icons.dart": emit_dart_icons(icons),
        ROOT / "crates/arcade-link/src/design/tokens.rs": emit_rust_tokens(tokens, icons),
        ROOT / "crates/arcade-link/src/paths/legacy_dirs.rs": emit_legacy_rust(dirs),
        ROOT / "qt/ArcadeAppDirsTable.inc": emit_legacy_qt(dirs),
        ROOT / "assets/tokens.json": emit_assets_tokens(tokens),
    }
    css = files[DESIGN / "css/arcade.css"]
    defined = set(re.findall(r"(--[\w-]+):", css))
    missing = sorted(used - defined)
    if missing:
        raise TokenError("components.css uses undefined custom properties: " + ", ".join(missing))
    for name, d, filled in icon_entries(icons):
        files[DESIGN / f"icons/{name}.svg"] = emit_icon_svg(d, filled)
    for glyph in sorted((DESIGN / "glyphs").glob("arcade.*.svg")):
        text = glyph.read_text(encoding="utf-8")
        files[ROOT / "assets/glyphs" / glyph.name] = text
        app = glyph.stem
        if app in tokens["accent"]:
            files[DESIGN / f"app-icons/{app.removeprefix('arcade.')}/icon.svg"] = app_icon_svg(text, tokens["accent"][app]["light"])
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if any generated file differs; write nothing")
    args = parser.parse_args()
    try:
        files = outputs()
    except TokenError as error:
        print(f"design tokens: {error}", file=sys.stderr)
        return 1
    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("out of date (run python3 design/generate.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print(f"design kit up to date ({len(files)} files; contrast and shortcut checks pass)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
