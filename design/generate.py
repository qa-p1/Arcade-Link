def emit_qml_format(ts: str) -> str:
    """Format.js for QML: format.ts without exports and type annotations."""
    body = ts.split("\n", 4)[4]  # drop the TypeScript file's header comment
    body = body.replace("export function", "function")
    body = re.sub(r"(\w)\?: (?:number|string)", r"\1", body)
    body = re.sub(r"(\w): (?:number|string)", r"\1", body)
    body = re.sub(r"\): (?:number|string) \{", ") {", body)
    if re.search(r":\s*(?:number|string|boolean)\b|\bexport\b", body):
        raise TokenError("design/css/format.ts uses TypeScript that Format.js can't strip")
    return f"// {HEADER} (from design/css/format.ts)\n.pragma library\n" + body


