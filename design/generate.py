DART_ICON_WIDGET = '''/// The icon's path scaled from the 24×24 grid to [size].
Path arcadeIconPath(String name, double size) {
  final ops = arcadeIconOps[name] ?? const <double>[];
  final s = size / 24;
  final path = Path();
  var i = 0;
  while (i < ops.length) {
    switch (ops[i].toInt()) {
      case 0:
        path.moveTo(ops[i + 1] * s, ops[i + 2] * s);
        i += 3;
      case 1:
        path.lineTo(ops[i + 1] * s, ops[i + 2] * s);
        i += 3;
      case 2:
        path.cubicTo(ops[i + 1] * s, ops[i + 2] * s, ops[i + 3] * s, ops[i + 4] * s, ops[i + 5] * s, ops[i + 6] * s);
        i += 7;
      default:
        path.close();
        i += 1;
    }
  }
  return path;
}

/// Paints one Arcade icon (stroke 1.5 on the 24 grid, or solid for filled icons).
class ArcadeIconPainter extends CustomPainter {
  ArcadeIconPainter(this.name, this.color);
  final String name;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final filled = arcadeFilledIcons.contains(name);
    final paint = Paint()
      ..color = color
      ..isAntiAlias = true
      ..style = filled ? PaintingStyle.fill : PaintingStyle.stroke
      ..strokeWidth = 1.5 * size.width / 24
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    canvas.drawPath(arcadeIconPath(name, size.width), paint);
  }

  @override
  bool shouldRepaint(ArcadeIconPainter oldDelegate) => oldDelegate.name != name || oldDelegate.color != color;
}

/// An Arcade icon widget; the colour defaults to the ambient icon colour.
class ArcadeIcon extends StatelessWidget {
  const ArcadeIcon(this.name, {super.key, this.size = 16, this.color, this.semanticLabel});
  final String name;
  final double size;
  final Color? color;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {
    final colour = color ?? IconTheme.of(context).color ?? const Color(0xff000000);
    final icon = CustomPaint(size: Size.square(size), painter: ArcadeIconPainter(name, colour));
    return semanticLabel == null ? ExcludeSemantics(child: icon) : Semantics(label: semanticLabel, child: icon);
  }
}'''


